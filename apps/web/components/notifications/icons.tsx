/** Render the correct glyph icon based on notification type */
export function NotifGlyphIcon({ glyphStyle, size = 16 }: { glyphStyle: string; size?: number }) {
  switch (glyphStyle) {
    case "memory": return <SunIcon size={size} />;
    case "together": return <UsersIcon size={size} />;
    case "sync": return <ClockIcon size={size} />;
    case "household": return <HomeIcon size={size} />;
    case "admin": return <AlertTriangleIcon size={size} />;
    case "activity": return <HeartIcon size={size} />;
    case "cover": return <ImageIcon size={size} />;
    default: return <ClockIcon size={size} />;
  }
}
